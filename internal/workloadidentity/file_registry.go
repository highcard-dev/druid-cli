package workloadidentity

import (
	"context"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sync"
)

// FileRegistry is daemon-owned state, separate from runtime data and backups.
type FileRegistry struct {
	revoked map[string]bool
	dir     string
	mu      sync.RWMutex
	records map[string]Record
}

func NewFileRegistry(dir string) (*FileRegistry, error) {
	if err := os.MkdirAll(dir, 0700); err != nil {
		return nil, err
	}
	if err := os.Chmod(dir, 0700); err != nil {
		return nil, err
	}
	r := &FileRegistry{dir: dir, records: map[string]Record{}, revoked: map[string]bool{}}
	data, err := os.ReadFile(filepath.Join(dir, "registry.json"))
	if err == nil {
		err = json.Unmarshal(data, &r.records)
	}
	if err != nil && !os.IsNotExist(err) {
		return nil, err
	}
	return r, nil
}

func (r *FileRegistry) save(records map[string]Record) error {
	data, err := json.Marshal(records)
	if err != nil {
		return err
	}
	file, err := os.CreateTemp(r.dir, ".registry-")
	if err != nil {
		return err
	}
	defer os.Remove(file.Name())
	if _, err := file.Write(data); err != nil {
		file.Close()
		return err
	}
	if err := file.Sync(); err != nil {
		file.Close()
		return err
	}
	if err := file.Close(); err != nil {
		return err
	}
	if err := os.Rename(file.Name(), filepath.Join(r.dir, "registry.json")); err != nil {
		return err
	}
	r.records = records
	return nil
}

func (r *FileRegistry) Ensure(_ context.Context, record Record) (CredentialMount, error) {
	r.mu.Lock()
	defer r.mu.Unlock()
	// IDs are generated by the daemon, but validate before using them as paths.
	if record.ExecutionID == "" || filepath.Base(record.ExecutionID) != record.ExecutionID || record.ExecutionID == "." || record.ExecutionID == ".." {
		return CredentialMount{}, fmt.Errorf("invalid execution ID")
	}
	path := filepath.Join(r.dir, record.ExecutionID)
	if r.revoked[record.ExecutionID] {
		return CredentialMount{}, ErrUnauthorized
	}
	for hash, existing := range r.records {
		if existing.ExecutionID == record.ExecutionID {
			if existing.DeploymentID != record.DeploymentID || existing.Command != record.Command {
				return CredentialMount{}, ErrUnauthorized
			}
			token, err := os.ReadFile(path)
			if err != nil || Hash(string(token)) != hash {
				return CredentialMount{}, ErrUnauthorized
			}
			return CredentialMount{Path: path}, nil
		}
	}
	if record.Recover {
		return CredentialMount{}, ErrUnauthorized
	}
	token, err := NewToken()
	if err != nil {
		return CredentialMount{}, err
	}
	// Parent directory is 0700. The bind-mounted file must also be readable by
	// non-root image users; it is mounted read-only into the execution.
	if err := r.writeToken(path, token); err != nil {
		return CredentialMount{}, err
	}
	updated := make(map[string]Record, len(r.records)+1)
	for key, value := range r.records {
		updated[key] = value
	}
	updated[Hash(token)] = record
	if err := r.save(updated); err != nil {
		os.Remove(path)
		return CredentialMount{}, err
	}
	return CredentialMount{Path: path}, nil
}

func (r *FileRegistry) writeToken(path, token string) error {
	file, err := os.CreateTemp(r.dir, ".token-")
	if err != nil {
		return err
	}
	defer os.Remove(file.Name())
	defer file.Close()
	if _, err := file.WriteString(token); err != nil {
		return err
	}
	if err := file.Chmod(0444); err != nil {
		return err
	}
	if err := file.Sync(); err != nil {
		return err
	}
	if err := file.Close(); err != nil {
		return err
	}
	return os.Rename(file.Name(), path)
}

func (r *FileRegistry) Lookup(_ context.Context, token string) (Record, error) {
	r.mu.RLock()
	defer r.mu.RUnlock()
	record, ok := r.records[Hash(token)]
	if !ok || r.revoked[record.ExecutionID] {
		return Record{}, ErrUnauthorized
	}
	return record, nil
}

func (r *FileRegistry) Records(_ context.Context) ([]Record, error) {
	r.mu.RLock()
	defer r.mu.RUnlock()
	records := make([]Record, 0, len(r.records))
	for _, record := range r.records {
		records = append(records, record)
	}
	return records, nil
}

func (r *FileRegistry) Revoke(_ context.Context, execution string) error {
	r.mu.Lock()
	defer r.mu.Unlock()
	r.revoked[execution] = true
	updated := make(map[string]Record, len(r.records))
	for key, record := range r.records {
		if record.ExecutionID != execution {
			updated[key] = record
		}
	}
	if err := r.save(updated); err != nil {
		return err
	}
	if err := os.Remove(filepath.Join(r.dir, execution)); err != nil && !os.IsNotExist(err) {
		return err
	}
	return nil
}

func (r *FileRegistry) Prune(_ context.Context, active map[string]bool) error {
	r.mu.Lock()
	defer r.mu.Unlock()
	files, err := os.ReadDir(r.dir)
	if err != nil {
		return err
	}
	known := map[string]bool{}
	for _, record := range r.records {
		known[record.ExecutionID] = true
	}
	for _, file := range files {
		if file.IsDir() || !executionFileName.MatchString(file.Name()) || known[file.Name()] || active[file.Name()] {
			continue
		}
		if err := os.Remove(filepath.Join(r.dir, file.Name())); err != nil {
			return err
		}
	}
	return nil
}
